// Writes src/lib/admin/pdf/fonts.generated.ts: the brand fonts (latin, WOFF)
// as data: URLs, so invoice PDFs render the same on the website's server, in
// the desktop app and in scheduled jobs — no font files to locate at runtime.
//
//   node scripts/gen-pdf-fonts.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FONTS = [
  ["SORA_400", "@fontsource/sora/files/sora-latin-400-normal.woff"],
  ["SORA_500", "@fontsource/sora/files/sora-latin-500-normal.woff"],
  ["GEIST_400", "@fontsource/geist/files/geist-latin-400-normal.woff"],
  ["GEIST_500", "@fontsource/geist/files/geist-latin-500-normal.woff"],
  ["GEIST_MONO_400", "@fontsource/geist-mono/files/geist-mono-latin-400-normal.woff"],
];

let out = "// GENERATED by scripts/gen-pdf-fonts.mjs from @fontsource (SIL Open Font License) — don't edit.\n";
for (const [name, file] of FONTS) {
  const b64 = readFileSync(join(root, "node_modules", file)).toString("base64");
  out += `export const ${name} = "data:font/woff;base64,${b64}";\n`;
}
const target = join(root, "src/lib/admin/pdf/fonts.generated.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`wrote ${FONTS.length} fonts → ${target.replace(root + "/", "")} (${Math.round(out.length / 1024)} KB)`);
