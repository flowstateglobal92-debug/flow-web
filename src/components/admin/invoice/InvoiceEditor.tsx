import Link from "next/link";
import { useRouter } from "next/navigation";
import { useDeferredValue, useEffect, useMemo, useState, type ReactNode } from "react";
import { createPortal } from "react-dom";
import { Icon } from "@/components/admin/icons";
import { useAction } from "@/components/admin/useAction";
import { Button, Checkbox, Field, Input, Notice, Panel, Select, Textarea, labelClass } from "@/components/admin/ui";
import { addDays, num } from "@/lib/admin/format";
import { computeTotals, type TaxInput } from "@/lib/admin/invoice-math";
import {
  CREDIT_REASONS,
  CURRENCIES,
  FREQUENCIES,
  addPeriods,
  blankItem,
  brandingFrom,
  businessFrom,
  cataloguePrice,
  clientAddress,
  docMoney,
  lineTax,
  type CatalogueItem,
  type ClientOption,
  type CreditReason,
  type DocStatus,
  type DocumentData,
  type DocumentInput,
  type EditorDoc,
  type EditorItem,
  type Frequency,
  type InvoiceSettings,
  type LeadOption,
  type ScheduleDraft,
  type ScheduleInput,
  type TaxRate,
} from "@/lib/admin/invoice-types";
